#!/usr/bin/env node
// Generate the routing canaries' graders/route.md FROM the routing table.
//
// A canary named evals/route-<task type>/ asks for the route of that task
// type; its graders/route.md is a regex over the final `ROUTE: <model>/<effort>`
// line. Hand-written, that regex went stale every time the table moved (the
// canaries were renamed after a route twice). Here the expected route comes
// from resolveRoute({ type, profile: false }) — the shipped table, never one
// machine's routing profile — so a table change is one regeneration.
//
// Usage:
//   node scripts/sync-eval-graders.mjs           # rewrite every evals/route-*/graders/route.md
//   node scripts/sync-eval-graders.mjs --check   # exit 1 if any disagrees with the table
//
// tests/evals-suite.test.mjs runs the --check path, so a table change that
// is not regenerated fails the suite.

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveRoute, taskTypeDef } from '../hooks/lib/context.mjs';

const PLUGIN_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const EVALS_DIR = join(PLUGIN_ROOT, 'evals');
const PREFIX = 'route-';

const esc = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function graderFor(type) {
  if (!taskTypeDef(type, { profile: false })) throw new Error(`evals/${PREFIX}${type}: "${type}" is not a task type in config/model-tiers.json`);
  const r = resolveRoute({ type, profile: false });
  if (!r || !r.model) throw new Error(`evals/${PREFIX}${type}: the table gives "${type}" no route (a parity type cannot be a route canary)`);
  const effortPart = r.effort ? `\\s*/\\s*${esc(r.effort)}\\b` : '\\b';
  const pattern = `ROUTE:\\s*\\**\\s*\`?\\s*(?:claude-)?${esc(r.model)}[-0-9.]*${effortPart}`;
  const route = `${r.model}${r.effort ? `/${r.effort}` : ''}`;
  return {
    route,
    text: [
      '---',
      `# GENERATED by scripts/sync-eval-graders.mjs from config/model-tiers.json — do not edit by hand.`,
      `# The final ROUTE line names ${route}, the route the table gives ${type}. Accepts the alias or a full ${r.model} id.`,
      'type: regex',
      `pattern: '${pattern}'`,
      'flags: i',
      '---',
      '',
    ].join('\n'),
  };
}

export function routeCanaries(dir = EVALS_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((d) => d.startsWith(PREFIX) && statSync(join(dir, d)).isDirectory())
    .map((d) => ({ dir: d, type: d.slice(PREFIX.length), file: join(dir, d, 'graders', 'route.md') }));
}

// [{ dir, type, route, ok }] — ok when the file on disk equals the generated text.
export function checkGraders(dir = EVALS_DIR) {
  return routeCanaries(dir).map((c) => {
    const g = graderFor(c.type);
    let cur = null;
    try { cur = readFileSync(c.file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    return { ...c, route: g.route, ok: cur === g.text };
  });
}

export function syncGraders(dir = EVALS_DIR) {
  const written = [];
  for (const c of routeCanaries(dir)) {
    const g = graderFor(c.type);
    let cur = null;
    try { cur = readFileSync(c.file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
    if (cur === g.text) continue;
    writeFileSync(c.file, g.text);
    written.push(c.dir);
  }
  return written;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const bad = checkGraders().filter((c) => !c.ok);
    if (!bad.length) { console.log('eval route graders match config/model-tiers.json'); process.exit(0); }
    for (const c of bad) console.error(`evals/${c.dir}/graders/route.md does not expect ${c.route}, the table's ${c.type} route`);
    console.error('Run `node scripts/sync-eval-graders.mjs` to regenerate.');
    process.exit(1);
  }
  const w = syncGraders();
  console.log(w.length ? `updated: ${w.map((d) => `evals/${d}/graders/route.md`).join(', ')}` : 'no eval graders needed updating');
}
